def construir():
    """Devuelve una lista de diccionarios listos para Producto."""
    filas = []
    for i, (marca, nombre, sub, precio) in enumerate(PRODUCTOS):
        cat, peso, dim, fragil, texto = SUBCATEGORIAS[sub]
        h = zlib.crc32(nombre.encode())
        original = None
        if i % 3 == 0:  # algunos con descuento para mostrar ofertas
            pct = (10, 12, 15, 20)[h % 4]
            original = int(round(precio / (1 - pct / 100) / 10) * 10)
        filas.append(dict(
            nombre=nombre, marca=marca, categoria=cat, subcategoria=sub,
            descripcion=f"{texto} Marca {marca}.",
            precio_mxn=precio, precio_original_mxn=original,
            peso_kg=round(peso * (0.9 + (h % 25) / 100), 2), dimension_max_cm=dim, fragil=fragil,
            existencias=0 if h % 23 == 0 else 3 + h % 38,
            rating=round(4.0 + (h % 10) / 10, 1), vendidos=20 + (h >> 3) % 2400,
            envio_gratis=precio >= 1500,
        ))
    return filas
